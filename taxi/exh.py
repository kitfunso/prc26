"""EXH (diagnostic, never a verdict): whether the 49 lane-A columns still hold anything MC2 has not taken.

The campaign has to choose between spending the remaining days on better use of the columns in hand (a hyperparameter search) and on new columns
(the queued Q1 and TH1 cells). Those need different work, and the choice has been argued from strategy, never measured. This measures it, by finding
the rows MC2 predicts identically and asking whether the features on which those rows differ say anything about how their taxi times differ.
"""
from __future__ import annotations

import numpy as np
import pandas as pd

from taxi.champ import COLS_D1, CURRENT, champion_holdout, lane_a
from taxi.l2 import floored

A_PER_COMP = 0.708  # one lane-A second in composite seconds, measured in docs/LEV.md
PRECISION = ((2, "0.01 s"), (1, "0.1 s"), (0, "1 s"), (-1, "10 s"))
TIE_DP = 2


def _pooled(y: np.ndarray, key: np.ndarray) -> tuple[float, int, int]:
    """Spread of the label within groups that share a prediction, which is the part of the error MC2 places no bet on."""
    d = pd.DataFrame({"k": key, "y": y})
    m = d[d.groupby("k")["y"].transform("count") >= 2]
    v = m.groupby("k")["y"].agg(["var", "count"])
    w = v["count"] - 1
    return float(np.sqrt((v["var"] * w).sum() / w.sum())), int(v.shape[0]), int(len(m))


def main() -> None:
    tra, tea = lane_a()
    p = floored(champion_holdout(CURRENT["A"], tra, tea))
    y = tea.y.values
    n = len(y)
    base = float(np.sqrt(((p - y) ** 2).mean()))
    out = [
        "# EXH: whether the 49 lane-A columns are exhausted\n",
        f"Generated by `python -m taxi.exh`. Champion {CURRENT['A']} on the lane-A holdout: {n:,} rows at {base:.4f} s.",
        "A diagnostic. It declares no cell and decides no verdict.\n",
        "## 1. The question it settles\n",
        "The queue holds both kinds of work: O1 searches hyperparameters over the columns already in hand, Q1 and TH1 add columns MC2 has never",
        "seen. Which goes first has been argued from strategy and never measured. It is measurable. Where MC2 gives two rows the same prediction it",
        "has declined to separate them, so the error there is spread it places no bet on. If the features those rows differ on predict how their",
        "taxi times differ, the columns still hold something and a better fit can reach it. If not, the columns are spent and only new ones help.\n",
        "## 2. How much of the error sits under a tie\n",
        "| prediction matched to | groups | rows | share | spread inside the ties | MC2 on those rows |",
        "|---|---|---|---|---|---|",
    ]
    for dp, nm in PRECISION:
        k = np.round(p, dp)
        pooled, ng, nr = _pooled(y, k)
        d = pd.DataFrame({"k": k, "e": p - y})
        sel = d.groupby("k")["e"].transform("count") >= 2
        out.append(f"| {nm} | {ng:,} | {nr:,} | {nr / n:.1%} | {pooled:.2f} s | {float(np.sqrt((d.e[sel] ** 2).mean())):.2f} s |")

    k = np.round(p, TIE_DP)
    tied = (pd.Series(k).groupby(k).transform("size") >= 2).values
    pooled, ng, nr = _pooled(y, k)
    on_tied = float(np.sqrt(((p[tied] - y[tied]) ** 2).mean()))
    misplaced = float(np.sqrt(max(on_tied**2 - pooled**2, 0.0)))
    out += [
        "",
        f"At the finest matching {nr / n:.1%} of lane A sits in a tie. MC2 scores {on_tied:.2f} s on those rows and {pooled:.2f} s of that is",
        f"spread among rows it treats as identical, leaving {misplaced:.2f} s for putting the tie itself in the wrong place. Almost all of the",
        "lane-A error is variation MC2 makes no attempt to predict.\n",
        "## 3. Are the tied rows actually identical?\n",
    ]
    sub = tea.loc[tied, list(COLS_D1)]
    fp = pd.util.hash_pandas_object(sub.astype(str).agg("|".join, axis=1), index=False).values
    g = pd.DataFrame({"k": k[tied], "fp": fp})
    per, size = g.groupby("k")["fp"].nunique(), g.groupby("k").size()
    ident = int((per == 1).sum())
    out += [
        f"No. Of {len(per):,} tied groups, {ident:,} ({ident / len(per):.1%}) have every row on the identical 49-feature vector; the median group",
        f"holds {per.median():.0f} distinct feature vectors across {size.median():.0f} rows. So the ties are MC2's own choice, not rows the data",
        "cannot tell apart. That is the case for the hyperparameter search: the information to split them is present, and a model with a different",
        "fit might use it.\n",
        "## 4. Does the information that differs say anything?\n",
        "Within each tied group, take each row's deviation from the group mean, on the label and on every numeric feature. If MC2 is leaving",
        "something on the table, a feature's deviation predicts the label's.\n",
    ]
    yy, kk = y[tied], k[tied]
    dy = yy - pd.Series(yy).groupby(kk).transform("mean").values
    num = [c for c in COLS_D1 if pd.api.types.is_numeric_dtype(tea[c])]
    cols, r = [], {}
    for c in num:
        v = sub[c].astype(float)
        v = v.fillna(v.median()).values
        dv = v - pd.Series(v).groupby(kk).transform("mean").values
        if dv.std() < 1e-9:
            continue
        cols.append(dv)
        r[c] = float(np.corrcoef(dv, dy)[0, 1])
    s = pd.Series(r).sort_values(key=abs, ascending=False)
    X = np.column_stack(cols)
    b, *_ = np.linalg.lstsq(X, dy, rcond=None)
    r2 = 1 - float(((dy - X @ b) ** 2).sum() / (dy**2).sum())
    gain = dy.std() * (1 - (1 - r2) ** 0.5)
    out += [
        f"Spread inside the ties: {dy.std():.1f} s over {int(tied.sum()):,} rows. The strongest single feature is `{s.index[0]}` at",
        f"{s.iloc[0]:+.4f}, and the five strongest are " + ", ".join(f"`{c}` {v:+.4f}" for c, v in s.head(5).items()) + ".\n",
        f"All {len(cols)} numeric features together give an in-sample R-squared of **{r2:.4f}**, worth about {gain:.2f} s of lane A",
        f"({gain * A_PER_COMP:.2f} s of composite) if every bit of it were real and none of it is, since the fit is in sample.\n",
        "Two limits, stated. The regression is linear, so a curved relation could hide from it; against that, CatBoost at depth 8 is the",
        "nonlinear model and it declined to split these rows. And the 49 columns include categoricals this measures nothing about; `docs/GEO.md`",
        "prices their ceiling separately at +2.330 s of lane A, which agrees.\n",
        "## 5. What it decides\n",
        "The columns in hand are spent. MC2 ties rows that do differ, but the differences carry nothing about the label, so a better fit over the",
        "same 49 columns has almost nothing to find. That ranks the queue: Q1 and TH1 add columns MC2 has never seen and keep their place ahead of",
        "O1, which searches hyperparameters over columns this measures as exhausted. The reorder in `scripts/queue-jobs.json` is now measured",
        "rather than argued, and O1 should be judged as a control on this result rather than as a source of gain.",
    ]
    with open("docs/EXH.md", "w", encoding="utf-8") as fh:
        fh.write("\n".join(out) + "\n")
    print("\n".join(out[-6:]))


if __name__ == "__main__":
    main()
