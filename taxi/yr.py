"""YR (diagnostic, never a verdict): how far the ten airports moved between 2025 and 2026, and whether anything we hold can correct for it.

Every model here trains on 2025 and is scored on 2026. The holdout is 2025, so it cannot see a year shift at all. MIX asked this once and found the
mean arrival taxi-in stable across the years, but it grouped by year and month and never by airport. Per airport the picture is different, and the
only bridge from the 2026 arrivals we hold to the 2026 departures we must predict turns out not to carry weight. Flag F23.
"""
from __future__ import annotations

import duckdb
import numpy as np
import pandas as pd

from taxi.champ import CURRENT, champion_holdout, lane_a
from taxi.data import _files, month_file
from taxi.l2 import floored

RANKING = "'data/ranking.parquet'"
HOLDOUT = (1, 7)
MONTHS = range(1, 13)
MIN_MONTHS = 6

BOTH = """SELECT CASE WHEN PHASE_mvt='ARR' THEN ADES_mvt ELSE ADEP_mvt END apt,
    month(MVT_TIME_UTC_mvt) m, PHASE_mvt ph, count(*) n, avg(TAXITIME_SEC_mvt) mu
  FROM read_parquet({src}) WHERE TAXITIME_SEC_mvt IS NOT NULL GROUP BY 1, 2, 3"""

ARRIVALS = """SELECT ADES_mvt apt, month(MVT_TIME_UTC_mvt) m, count(*) n, avg(TAXITIME_SEC_mvt) mu
  FROM read_parquet({src}) WHERE PHASE_mvt='ARR' AND TAXITIME_SEC_mvt IS NOT NULL
    AND month(MVT_TIME_UTC_mvt) IN (1, 7) GROUP BY 1, 2"""


def _panel(con: duckdb.DuckDBPyConnection, files: str) -> pd.DataFrame:
    """One row per airport-month with both directions' mean taxi time, plus each one's deviation from that airport's own year."""
    q = con.execute(BOTH.format(src=files)).df()
    w = q.pivot_table(index=["apt", "m"], columns="ph", values="mu").dropna().reset_index()
    for col in ("ARR", "DEP"):
        w["d" + col] = w[col] - w.groupby("apt")[col].transform("mean")
    return w


def main() -> None:
    con = duckdb.connect()
    files = _files([month_file(m) for m in MONTHS])
    panel = _panel(con, files)
    a25 = con.execute(ARRIVALS.format(src=files)).df()
    a26 = con.execute(ARRIVALS.format(src=RANKING)).df()
    d = a25.merge(a26, on=["apt", "m"], suffixes=("_25", "_26"))
    d["move"] = d.mu_26 - d.mu_25
    wtd = float((d.move * d.n_26).sum() / d.n_26.sum())

    out = [
        "# YR: what moved between 2025 and 2026, and why we cannot correct for it\n",
        "Generated by `python -m taxi.yr`. A diagnostic. It declares no cell and decides no verdict.\n",
        "## 1. The exposure\n",
        "Every model in this campaign trains on 2025 and is scored on 2026, and the holdout is 2025, so nothing measured on it can see a year",
        "shift. `docs/MIX.md` asked this once and found mean arrival taxi-in stable across the years. That grouping was year and month, never",
        "airport. The ranking file keeps a measured taxi-in on all of its arrivals, so the per-airport version is available and is below.\n",
        "## 2. Arrival taxi-in per airport, the same months the holdout uses\n",
        "| airport | month | 2025 | 2026 | change |",
        "|---|---|---|---|---|",
    ]
    for r in d.sort_values(["apt", "m"]).itertuples():
        out.append(f"| {r.apt} | {r.m} | {r.mu_25:.1f} s | {r.mu_26:.1f} s | **{r.move:+.1f} s** |")
    jan, jul = d[d.m == 1], d[d.m == 7]
    out += [
        "",
        f"The aggregate is quiet at {wtd:+.2f} s weighted, which is why MIX read it as stable, but the airports are not. The largest move is",
        f"{d.move.abs().max():.1f} s and the sign follows the month: {int((jan.move > 0).sum())} of {len(jan)} airports slower in January",
        f"2026, {int((jul.move < 0).sum())} of {len(jul)} faster in July. Those cancel in the mean and do not cancel in a squared error.\n",
        "## 3. Whether arrivals can speak for departures\n",
        "Nothing here has 2026 departure taxi times, so a 2026 departure shift cannot be measured, only inferred from the arrivals. That",
        "inference needs arrival and departure taxi times to move together. Across 2025 they do not. Each airport-month below is one point,",
        "with each direction taken as a deviation from that airport's own year.\n",
        "| airport | months | correlation | slope |",
        "|---|---|---|---|",
    ]
    for a, g in panel.groupby("apt"):
        if len(g) < MIN_MONTHS:
            continue
        out.append(f"| {a} | {len(g)} | {np.corrcoef(g.dARR, g.dDEP)[0, 1]:+.3f} | {np.polyfit(g.dARR, g.dDEP, 1)[0]:+.3f} |")
    pooled_r = float(np.corrcoef(panel.dARR, panel.dDEP)[0, 1])
    out += [
        "",
        f"Pooled over all {len(panel)} airport-months the correlation is **{pooled_r:+.3f}**. The per-airport figures run from",
        f"{panel.groupby('apt').apply(lambda g: np.corrcoef(g.dARR, g.dDEP)[0, 1], include_groups=False).min():+.3f} to",
        f"{panel.groupby('apt').apply(lambda g: np.corrcoef(g.dARR, g.dDEP)[0, 1], include_groups=False).max():+.3f} and change sign between",
        "airports, on twelve points each, which is inside the noise of a correlation at that sample size. Taxi-in has no takeoff queue in it;",
        "taxi-out is mostly queue. They share a surface and little else.\n",
        "## 4. The correction, applied and refused\n",
        "Fitting each airport's slope on the ten months the holdout does not use, then correcting the holdout by its arrival deviation, loses.\n",
        "| correction | holdout RMSE | change |",
        "|---|---|---|",
    ]
    tra, tea = lane_a()
    p = floored(champion_holdout(CURRENT["A"], tra, tea))
    y = tea.y.values
    base = float(np.sqrt(((p - y) ** 2).mean()))
    fit = panel[~panel.m.isin(HOLDOUT)]
    slopes = {a: float(np.polyfit(g.dARR, g.dDEP, 1)[0]) for a, g in fit.groupby("apt") if len(g) >= MIN_MONTHS}
    pooled = float(np.polyfit(fit.dARR, fit.dDEP, 1)[0])
    dev = panel.set_index(["apt", "m"]).dARR
    key = list(zip(tea.apt.astype(str), tea.month.astype(int)))
    for nm, f in (("pooled slope", lambda a: pooled), ("per-airport slope", lambda a: slopes.get(a, pooled))):
        off = np.array([f(a) * dev.get((a, m), 0.0) for a, m in key])
        r = float(np.sqrt(((p + off - y) ** 2).mean()))
        out.append(f"| {nm} | {r:.4f} s | {base - r:+.4f} s |")
    out += [
        "",
        f"Against MC2's {base:.4f} s both lose, the per-airport version by more than the 2 s floor. The bridge does not hold, so the correction",
        "is refused rather than parked.\n",
        "## 5. Flag F23\n",
        f"The ten airports moved by up to {d.move.abs().max():.0f} s of arrival taxi-in between 2025 and 2026, in a direction that follows the",
        "month. Whether departures moved with them is unknown and unknowable from what we hold: there is one year of departure labels, and the",
        "only proxy for the second year fails its own test. So the board score carries a year-shift risk that no holdout number reflects and no",
        "correction available to us removes. Every projection from holdout to board in this campaign inherits it. Recorded, not corrected.",
    ]
    with open("docs/YR.md", "w", encoding="utf-8") as fh:
        fh.write("\n".join(out) + "\n")
    print("\n".join(out[-6:]))


if __name__ == "__main__":
    main()
