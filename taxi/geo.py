"""GEO (diagnostic, never a verdict): the ceiling on airport surface geometry, measured without fetching any geometry.

Taxi time is distance over speed, and no column in the 30 raw fields is a distance. Stand-to-runway distance from open map data is the obvious
missing feature and has never been tried. It does not need to be fetched to be priced: any such feature is a function of (airport, stand, runway),
so the composite it can free is capped by what those three columns still explain in the champion's own residuals. That cap is what this measures.
"""
from __future__ import annotations

import numpy as np
import pandas as pd

from taxi.champ import CURRENT, champion_holdout, champion_oof, lane_a
from taxi.l2 import floored

A_PER_COMP = 0.708  # one lane-A second in composite seconds, measured in docs/LEV.md
SHRINK = (0, 5, 20, 50, 100, 200, 400, 800, 1600)
BANDS = ((0, 20, "under 20"), (20, 100, "20 to 99"), (100, 500, "100 to 499"), (500, 10**9, "500 or more"))
REPS = 5


def _cells(df: pd.DataFrame) -> tuple[pd.Series, pd.Series]:
    apt = df.apt.astype(str)
    stand = apt + "|" + df.stand.astype(str)
    return stand, stand + "/" + df.runway.astype(str)


def _dropped(e: np.ndarray, key: np.ndarray, n: int, mask: np.ndarray | None = None) -> float:
    """Mean squared error removed over all n rows by knowing each cell's own mean residual, which makes the bands below add up."""
    m = slice(None) if mask is None else mask
    g = pd.DataFrame({"k": key[m], "e": e[m]}).groupby("k")["e"].agg(["mean", "count"])
    return float((g["count"] * g["mean"] ** 2).sum() / n)


def ceiling(e: np.ndarray, key: np.ndarray, mask: np.ndarray | None = None, seed: int = 0) -> float:
    """Lane-A seconds freed by the cell means, less what the same cell count frees from shuffled residuals; fitting k means to n rows pays off by chance alone."""
    rng = np.random.default_rng(seed)
    n = len(e)
    mse = float((e**2).mean())
    raw = _dropped(e, key, n, mask)
    null = float(np.mean([_dropped(e[rng.permutation(n)], key, n, mask) for _ in range(REPS)]))
    return mse**0.5 - (mse - (raw - null)) ** 0.5


def _shrunk(k_tr: pd.Series, e_tr: np.ndarray, k_te: pd.Series, k: float) -> np.ndarray:
    g = pd.DataFrame({"k": k_tr, "e": e_tr}).groupby("k")["e"].agg(["mean", "count"])
    return k_te.map(g["mean"] * g["count"] / (g["count"] + k)).fillna(0.0).values


def main() -> None:
    tra, tea = lane_a()
    eh = floored(champion_holdout(CURRENT["A"], tra, tea)) - tea.y.values
    eo = floored(champion_oof(CURRENT["A"], tra)) - tra.y.values
    base = float(np.sqrt((eh**2).mean()))
    n = len(eh)
    st_o, sr_o = _cells(tra)
    st_h, sr_h = _cells(tea)
    out = [
        "# GEO: what airport surface geometry could be worth, priced without fetching it\n",
        f"Generated by `python -m taxi.geo`. Champion {CURRENT['A']} on the lane-A holdout: {n:,} rows at {base:.4f} s.",
        "A diagnostic. It declares no cell and decides no verdict.\n",
        "## 1. Why the question came up\n",
        "None of the 30 raw columns is a distance, and taxi time is distance over speed. Stand-to-runway distance from open map data is the",
        "largest single piece of physics the model has never been given. Fetching it means matching stand names to map features at ten airports.",
        "That work is only worth starting if the ceiling clears the 2 s floor, and the ceiling can be measured from columns already in hand.\n",
        "## 2. The bound\n",
        "Stand-to-runway distance is fixed by the airport, the stand and the runway. Any geometric feature is therefore a function of those three",
        "columns, all three of which MC2 already carries. Its main effect cannot free more than the cell identities still explain in MC2's residuals.",
        "The table removes each cell's own mean residual, then subtracts what the same number of cells removes from shuffled residuals, because",
        "fitting thousands of means to 339,046 rows pays a little by chance alone.\n",
        "| grouping | cells | raw | chance | honest ceiling | composite |",
        "|---|---|---|---|---|---|",
    ]
    for nm, key in (("airport", tea.apt.astype(str)), ("airport + runway", tea.apt.astype(str) + "/" + tea.runway.astype(str)),
                    ("airport + stand", st_h), ("airport + stand + runway", sr_h)):
        k = key.values
        rng = np.random.default_rng(0)
        mse = float((eh**2).mean())
        raw = _dropped(eh, k, n)
        null = float(np.mean([_dropped(eh[rng.permutation(n)], k, n) for _ in range(REPS)]))
        hon = ceiling(eh, k)
        rc, nc = base - (mse - raw) ** 0.5, base - (mse - null) ** 0.5
        out.append(f"| {nm} | {len(set(k)):,} | {rc:+.3f} s | {nc:+.3f} s | **{hon:+.3f} s** | {hon * A_PER_COMP:+.3f} s |")

    sr_ceil = ceiling(eh, sr_h.values)
    out += [
        "",
        f"So every stand-and-runway geometric feature put together is capped at **{sr_ceil:+.3f} s of lane A**, or",
        f"**{sr_ceil * A_PER_COMP:+.3f} s of composite**, before one byte of map data is fetched. The 2 s floor is 2 s of lane A.",
        "The cap is measured on the holdout's own rows, so a real feature estimated from training months can only come in under it.\n",
        "## 3. How much of that cap survives the calendar\n",
        "The cap assumes the holdout's own cell means are known. A model has to estimate them from the training months and carry them forward.",
        "This is that estimate: each cell's mean out-of-fold residual over the training months, shrunk toward zero by k, applied to the holdout.\n",
        "| estimator | best k | holdout | gain lane A | composite | share of cap |",
        "|---|---|---|---|---|---|",
    ]
    best = 0.0
    for nm, k_o, k_h, stat in (("stand x runway", sr_o, sr_h, "mean"), ("stand only", st_o, st_h, "mean")):
        scored = [(k, float(np.sqrt(((eh - _shrunk(k_o, eo, k_h, k)) ** 2).mean()))) for k in SHRINK]
        k, r = min(scored, key=lambda t: t[1])
        best = max(best, base - r)
        out.append(f"| {nm}, {stat} | {k} | {r:.4f} s | {base - r:+.4f} s | {(base - r) * A_PER_COMP:+.3f} s | {(base - r) / sr_ceil:.0%} |")
    out += [
        "",
        f"The best transferable estimate is **{best:+.3f} s of lane A**, {best * A_PER_COMP:+.3f} s of composite: {best / sr_ceil:.0%} of the cap.",
        "The rest of the cap is holdout-specific noise that no feature can carry forward. This also explains G1's tie: it attacked the stand level,",
        "which holds less than the pair, with an estimator that lands in the same place.\n",
        "## 4. Where the cap sits, and the one argument left for geometry\n",
        "Target encoding shrinks a thin cell toward zero, so it is structurally blind where few training rows back the cell. A distance is not:",
        "it generalises across cells. If the cap sat mostly in thin cells, geometry could reach what the encoding cannot. The bands add to the total.\n",
        "| training rows behind the cell | holdout rows | share | honest ceiling |",
        "|---|---|---|---|",
    ]
    cnt = sr_h.map(sr_o.value_counts()).fillna(0).values
    for lo, hi, nm in BANDS:
        m = (cnt >= lo) & (cnt < hi)
        out.append(f"| {nm} | {int(m.sum()):,} | {m.sum() / n:.1%} | {ceiling(eh, sr_h.values, m):+.3f} s |")

    qb = pd.qcut(tea.queue.rank(method="first"), 3, labels=["low", "mid", "high"]).astype(str).values
    both = ceiling(eh, np.char.add(np.char.add(sr_h.values.astype(str), "@"), qb))
    out += [
        "",
        "Thin cells hold a third of the cap on under a fiftieth of the rows, which is the strongest ground the geometry case has. It is still",
        "under a second of lane A on its own.\n",
        "One channel escapes the bound in section 2. Queue time plausibly scales with distance, and a distance times congestion term is not a",
        "function of the three columns alone. Splitting every cell by congestion tercile prices that channel too.\n",
        f"- cell alone: **{sr_ceil:+.3f} s** of lane A",
        f"- cell by congestion tercile: **{both:+.3f} s**",
        f"- so the interaction channel adds **{both - sr_ceil:+.3f} s** of lane A, {(both - sr_ceil) * A_PER_COMP:+.3f} s of composite\n",
        "## 5. What this closes\n",
        f"Everything airport surface geometry could touch, main effect and congestion interaction together, is capped at **{both:+.3f} s of lane A**",
        f"or **{both * A_PER_COMP:+.3f} s of composite**, measured with the holdout's own answers in hand. At the {best / sr_ceil:.0%} rate at which this",
        f"kind of structure has been shown to survive the calendar, the realistic figure is near {both * best / sr_ceil * A_PER_COMP:+.3f} s of composite.",
        "The residual gap to first place is 5.4 to 10.1 s of composite. Fetching stand geometry for ten airports cannot close it, and the ceiling",
        "for the whole direction sits under the floor a verdict would have to clear. The direction is priced, not guessed, and it stays closed.",
    ]
    with open("docs/GEO.md", "w", encoding="utf-8") as fh:
        fh.write("\n".join(out) + "\n")
    print("\n".join(out[-8:]))


if __name__ == "__main__":
    main()
